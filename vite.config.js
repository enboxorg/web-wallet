var browserPkg = JSON.parse(fs.readFileSync(path.resolve(__dirname, 'node_modules/@enbox/browser/package.json'), 'utf-8'));
var browserVersion = browserPkg.version;
/**
 * Replaces `__PRODUCT_BRAND__` in index.html with the product brand slug so
 * static brand assets (e.g. the Open Graph image) follow the product accent:
 * `VITE_PRODUCT_THEME=blue` → blue assets, `orange` → orange assets, default → rose.
 * The logo variants are generated by `scripts/generate-brand-assets.mjs`.
 */
function productBrandPlugin(brand) {
    return {
        name: 'enbox-product-brand',
        transformIndexHtml: function (html) {
            return html.replaceAll('__PRODUCT_BRAND__', brand);
        },
    };
}
/**
 * Emits `/.well-known/enbox-connect` tailored to the active product theme
 * (or `VITE_CONNECT_SERVER_URL`) so the Cloudflare `orange` build advertises
 * its matching Connect relay rather than the legacy Fly default copied from
 * `public/.well-known/enbox-connect`.
 */
function connectDiscoveryPlugin(connectServerUrl) {
    var payload = "".concat(JSON.stringify({ connectServerUrl: connectServerUrl }, null, 2), "\n");
    var resolvedOutDir = path.resolve(__dirname, 'dist');
    return {
        name: 'enbox-connect-discovery',
        configResolved: function (config) {
            resolvedOutDir = path.resolve(config.root, config.build.outDir);
        },
        configureServer: function (server) {
            server.middlewares.use('/.well-known/enbox-connect', function (_req, res) {
                res.setHeader('Content-Type', 'application/json');
                res.setHeader('Access-Control-Allow-Origin', '*');
                res.end(payload);
            });
        },
        writeBundle: function (options) {
            var outDir = options.dir ? path.resolve(options.dir) : resolvedOutDir;
            var target = path.join(outDir, '.well-known', 'enbox-connect');
            fs.mkdirSync(path.dirname(target), { recursive: true });
            fs.writeFileSync(target, payload, 'utf-8');
        },
    };
}
function resolveProductBrand(theme) {
    if (theme === 'blue')
        return 'blue';
    if (theme === 'orange')
        return 'orange';
    return 'rose';
}
