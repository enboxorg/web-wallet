import { defineConfig, loadEnv, type Plugin } from 'vite';
import fs from 'fs';
import path from 'path';
import react from '@vitejs/plugin-react';
import svgr from 'vite-plugin-svgr';
import tailwindcss from '@tailwindcss/vite';
import nodePolyfills from 'vite-plugin-node-stdlib-browser';
import { VitePWA } from 'vite-plugin-pwa';

const browserPkg = JSON.parse(fs.readFileSync(
  path.resolve(__dirname, 'node_modules/@enbox/browser/package.json'), 'utf-8',
));
const browserVersion = browserPkg.version as string;

/**
 * Replaces `__PRODUCT_BRAND__` in index.html with the product brand slug so
 * static brand assets (e.g. the Open Graph image) follow the product accent:
 * `VITE_PRODUCT_THEME=blue` → blue assets, `orange` → orange assets, default → rose.
 * The logo variants are generated by `scripts/generate-brand-assets.mjs`.
 */
function productBrandPlugin(brand: string): Plugin {
  return {
    name: 'enbox-product-brand',
    transformIndexHtml(html) {
      return html.replaceAll('__PRODUCT_BRAND__', brand);
    },
  };
}

/**
 * Emits `/.well-known/enbox-connect` tailored to the active product theme
 * (or `VITE_CONNECT_SERVER_URL`) so the Cloudflare `orange` build advertises
 * its matching Connect relay rather than the legacy Fly default copied from
 * `public/.well-known/enbox-connect`.
 */
function connectDiscoveryPlugin(connectServerUrl: string): Plugin {
  const payload = `${JSON.stringify({ connectServerUrl }, null, 2)}\n`;
  let resolvedOutDir = path.resolve(__dirname, 'dist');

  return {
    name: 'enbox-connect-discovery',
    configResolved(config) {
      resolvedOutDir = path.resolve(config.root, config.build.outDir);
    },
    configureServer(server) {
      server.middlewares.use('/.well-known/enbox-connect', (_req, res) => {
        res.setHeader('Content-Type', 'application/json');
        res.setHeader('Access-Control-Allow-Origin', '*');
        res.end(payload);
      });
    },
    writeBundle(options) {
      const outDir = options.dir ? path.resolve(options.dir) : resolvedOutDir;
      const target = path.join(outDir, '.well-known', 'enbox-connect');
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, payload, 'utf-8');
    },
  };
}

function resolveProductBrand(theme: string | undefined): 'blue' | 'orange' | 'rose' {
  if (theme === 'blue') return 'blue';
  if (theme === 'orange') return 'orange';
  return 'rose';
}

export default defineConfig(({ mode }) => {
  const env = loadEnv(mode, process.cwd(), '');
  const brand = resolveProductBrand(env.VITE_PRODUCT_THEME);
  const connectServerUrl = env.VITE_CONNECT_SERVER_URL?.trim() || (
    brand === 'orange'
      ? 'https://cf-east.dwn.enbox.id/connect'
      : 'https://enbox-dwn.fly.dev/connect'
  );

  return {
    base: '/',
    resolve: {
      alias: {
        '@': path.resolve(__dirname, './src'),
      },
    },
    define: {
      global                          : 'globalThis',
      '__ENBOX_BROWSER_SDK_VERSION__' : JSON.stringify(browserVersion),
    },
    plugins: [
      tailwindcss(),
      svgr(),
      react(),
      nodePolyfills(),
      productBrandPlugin(brand),
      connectDiscoveryPlugin(connectServerUrl),
      VitePWA({
        strategies: 'injectManifest',
        srcDir: 'src',
        filename: 'sw.ts',
        registerType: 'prompt',
        injectRegister: false,

        // PWA icons are pre-generated per brand and committed under
        // `public/pwa-icons/<brand>/` — the build-time pwaAssets integration
        // (and its sharp/sharp-ico/@vite-pwa/assets-generator dependency
        // chain) is intentionally not used. Regenerate via
        // `scripts/generate-brand-assets.mjs` (see that file's header).
        manifest: {
          name: 'Enbox Wallet',
          short_name: 'Enbox',
          description: 'Your digital identity wallet — manage DIDs, protocols, and encrypted data',
          theme_color: '#0a0a0f',
          background_color: '#0a0a0f',
          icons: [
            { src: `pwa-icons/${brand}/pwa-64x64.png`, sizes: '64x64', type: 'image/png' },
            { src: `pwa-icons/${brand}/pwa-192x192.png`, sizes: '192x192', type: 'image/png' },
            { src: `pwa-icons/${brand}/pwa-512x512.png`, sizes: '512x512', type: 'image/png' },
            { src: `pwa-icons/${brand}/maskable-icon-512x512.png`, sizes: '512x512', type: 'image/png', purpose: 'maskable' },
          ],
        },

        injectManifest: {
          maximumFileSizeToCacheInBytes: 5_000_000,
          globPatterns: ['**/*.{js,css,html,json,svg,png,ico}'],
        },

        devOptions: {
          enabled: true,
          navigateFallback: 'index.html',
          suppressWarnings: false,
          type: 'module',
        },
      }),
    ],
    build: {
      chunkSizeWarningLimit: 3000,
      rollupOptions: {
        output: {
          manualChunks(id: string) {
            if (id.includes('node_modules')) {
              // Keep React framework in its own chunk
              if (
                id.includes('react-dom') ||
                id.includes('react-router') ||
                id.includes('/react/')
              )
                return 'vendor-react';
              // UI libraries (no circular deps with SDK)
              if (
                id.includes('@tanstack') ||
                id.includes('zustand') ||
                id.includes('sonner') ||
                id.includes('lucide') ||
                id.includes('clsx') ||
                id.includes('qrcode')
              )
                return 'vendor-ui';
              // Everything else (including @enbox/* and its transitive deps
              // like node-stdlib-browser, multiformats, etc.) stays in one
              // chunk to avoid circular-dependency initialisation errors.
            }
          },
        },
      },
    },
  };
});
